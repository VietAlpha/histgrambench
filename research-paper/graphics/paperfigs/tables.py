# --------------------------------------------------------------------------- Table 2
def table2() -> list[Path]:
    th = data.thresholds()
    counts: collections.Counter = collections.Counter()
    judged = 0
    for d in data.scored_items():
        for f in data.card(d["id"])["facts"]:
            if f["eligible"]:
                counts[f["class"]] += 1
                judged += f["decidability"] == "model"
    total = sum(counts.values())

    def share(c): return f"{100 * counts[c] / total:.0f}"

    eps, deg = th.value("eps_on_frac"), th.value("parallel_deg")
    if th.value("perpendicular_deg") != deg:
        raise RuntimeError("parallel and perpendicular tolerances differ; the table states one angle")
    tex_rows = [
        ["Entity", r"$\mathrm{point}(P)$, $\mathrm{circle}(C)$", "Present in drawing", share("entity")],
        ["Relation", r"$\mathrm{on}(P, C)$, $\mathrm{parallel}(\ell_1, \ell_2)$",
         rf"$d \le {eps:g}\,D$; $\angle \le {deg:g}^\circ$", share("relation")],
        ["Label", r"$\mathrm{label}(P, \textrm{``A''})$", "Exact string, bound to entity", share("label")],
    ]
    md_rows = [
        ["Entity", "point(P), circle(C)", "Present in drawing", share("entity")],
        ["Relation", "on(P, C), parallel(ℓ₁, ℓ₂)", f"d ≤ {eps:g} D; angle ≤ {deg:g}°", share("relation")],
        ["Label", "label(P, \"A\")", "Exact string, bound to entity", share("label")],
    ]
    pj = f"{100 * judged / total:.2f}"
    cap_tex = (f"Answer-key fact classes ($n =$ {total:,}). $D$: drawing diagonal. {pj}\\% of facts are decided by "
               f"the judge panel.")
    cap_md = f"Answer-key fact classes (n = {total:,}). D: drawing diagonal. {pj}% of facts are decided by the judge panel."
    return _simple_table("table2_facts", "tab:facts", (cap_tex, cap_md),
                         (["Class", "Example", "Criterion", r"Share (\%)"], ["Class", "Example", "Criterion", "Share (%)"]),
                         (tex_rows, md_rows),
                         r"@{}l >{\raggedright\arraybackslash}X >{\raggedright\arraybackslash}X r@{}")


# --------------------------------------------------------------------------- Table 3
def table3() -> list[Path]:
    rep = data.scores()
    A, B = rep["tables"]["A"], rep["tables"]["B"]
    ce = rep["context_effect"]
    models = data.model_order("A")
    cols = {  # column -> value per model (higher is better for every marked column)
        "HA": {m: A["models"][m]["headline"]["estimate"] for m in models},
        "HB": {m: B["models"][m]["headline"]["estimate"] for m in models},
        "VA": {m: A["models"][m]["validity"]["Valid@1"] for m in models},
        "E": {m: A["models"][m]["per_class"]["recall"]["E"]["R"] for m in models},
        "R": {m: A["models"][m]["per_class"]["recall"]["R"]["R"] for m in models},
        "L": {m: A["models"][m]["per_class"]["recall"]["L"]["R"] for m in models},
    }
    # Best and second-best are decided on the displayed (rounded) values, so equal-looking cells mark alike.
    pct = ("VA",)
    shown = {c: {m: round(v[m] * (100 if c in pct else 1), 1 if c in pct else 3) for m in models}
             for c, v in cols.items()}
    top = {c: sorted(set(v.values()), reverse=True)[:2] for c, v in shown.items()}

    def cell(c, m, text, tex):
        if shown[c][m] == top[c][0]:
            return (f"\\textbf{{{text}}}" if tex else f"**{text}**")
        if shown[c][m] == top[c][1]:
            return (f"\\underline{{{text}}}" if tex else f"<u>{text}</u>")
        return text

    def sgn(x, tex):
        s = f"{x:+.3f}"
        return s.replace("-", "$-$") if tex else s.replace("-", "−")

    lines = {True: [], False: []}
    for tex in (True, False):
        for m in models:
            lines[tex].append([style.MODEL_NAMES[m],
                               cell("HA", m, f"{cols['HA'][m]:.3f}", tex), cell("HB", m, f"{cols['HB'][m]:.3f}", tex),
                               cell("VA", m, f"{100 * cols['VA'][m]:.1f}", tex),
                               cell("E", m, f"{cols['E'][m]:.3f}", tex), cell("R", m, f"{cols['R'][m]:.3f}", tex),
                               cell("L", m, f"{cols['L'][m]:.3f}", tex)])
    p = ce["pooled"]
    N, G = A["N"], A["models"][models[0]]["headline"]["G"]
    pooled = {True: (f"Pooled $\\Delta H$ (B $-$ A) $=$ {sgn(p['estimate'], True)}, 95\\% CI "
                     f"[{sgn(p['ci'][0], True)}, {sgn(p['ci'][1], True)}]"),
              False: (f"Pooled ΔH (B − A) = {sgn(p['estimate'], False)}, 95% CI "
                      f"[{sgn(p['ci'][0], False)}, {sgn(p['ci'][1], False)}]")}
    cap = (f"Main results ($N =$ {N:,} items, $G = {G}$ source groups). $H$: group-mean item score. Valid: "
           f"share of outputs yielding a drawing. Recall by fact class. Bold: best; underline: second.")
    tex = rf"""% Generated by research-paper/graphics/paperfigs/tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{{cap}}}
\label{{tab:results}}
\small
\begin{{tabular}}{{@{{}}l cc c ccc@{{}}}}
\toprule
 & \multicolumn{{2}}{{c}}{{$H$}} & \multicolumn{{4}}{{c}}{{Track A}} \\
\cmidrule(lr){{2-3}} \cmidrule(l){{4-7}}
Model & Track A & Track B & Valid (\%) & Entity & Relation & Label \\
\midrule
{chr(10).join(" & ".join(r) + r" \\" for r in lines[True])}
\midrule
\multicolumn{{7}}{{@{{}}l}}{{{pooled[True]}}} \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    md = ("| Model | H, Track A | H, Track B | Valid A (%) | Recall A: entity | Recall A: relation | "
          "Recall A: label |\n|---|---|---|---|---|---|---|\n"
          + "\n".join("| " + " | ".join(r) + " |" for r in lines[False])
          + f"\n\n{pooled[False]}\n\n"
          + cap.replace("$N =$", "N =").replace("$G = ", "G = ").replace("$H$", "H").replace(f"{G}$", f"{G}")
          + "\n")
    return _write("table3_results", tex, md)


