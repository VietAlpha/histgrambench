def tableS5_key_retention() -> list[Path]:
    k = data.key_retention()
    n_key = sum(k["eligible_by_class"].values())
    total_t2 = sum(sum(f["eligible"] for f in data.card(d["id"])["facts"]) for d in data.scored_items())
    if n_key != total_t2:
        raise RuntimeError(f"key-retention tally ({n_key}) differs from the scored keys ({total_t2})")
    classes = [("entity", "Entity"), ("relation", "Relation"), ("label", "Label")]
    order = data.model_order("A")
    pred = sorted(k["relation_pred_retention"].items(), key=lambda kv: -kv[1][1])
    half = (len(pred) + 1) // 2
    out = {}
    for tex in (True, False):
        a = [[lab, f"{k['union_by_class'][c]:,}", f"{k['eligible_by_class'][c]:,}",
              f"{100 * k['retention_by_class'][c]:.1f}",
              f"{100 * k['support_mix'][f'{c}|both_generated'] / k['eligible_by_class'][c]:.1f}"] for c, lab in classes]
        b = [[style.MODEL_NAMES[m]] + [f"{k['present_by_support'][m][f'{c}|{s}']:.2f}"
                                       for c, _ in classes for s in ("both_generated", "one_generated")] for m in order]
        cl = [[_tt(p, tex), f"{v[1]:,}", f"{100 * v[2]:.0f}"] for p, v in pred]
        cl += [["", "", ""]] * (2 * half - len(cl))
        c = [cl[i] + cl[i + half] for i in range(half)]
        out[tex] = (a, b, c)
    cap = (f"Answer-key retention under the unanimity rule ($n =$ {n_key:,} retained facts). (a) Facts in the union "
           f"of both writers and facts retained, by class; both: share of retained facts that both writers generated. "
           f"(b) Share of checkable retained facts recovered on valid Track A drawings, by whether both writers or one "
           f"generated the fact. (c) Retention by predicate.")
    a, b, c = out[True]

    def tab(colspec, head, rows, extra=""):
        return (rf"\begin{{tabular}}{{{colspec}}}" + "\n\\toprule\n" + extra + head + r" \\" + "\n\\midrule\n"
                + "\n".join(" & ".join(r) + r" \\" for r in rows) + "\n\\bottomrule\n\\end{tabular}")
    sub_b = r" & \multicolumn{2}{c}{Entity} & \multicolumn{2}{c}{Relation} & \multicolumn{2}{c}{Label} \\" + \
        "\n" + r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(l){6-7}" + "\n"
    ta = tab("@{}l rrrr@{}", r"Class & Union & Retained & Retention (\%) & Both (\%)", a)
    tb = tab("@{}l rr rr rr@{}", "Model & Both & One & Both & One & Both & One", b, sub_b)
    tc = tab(r"@{}l rr @{\hspace{2.5em}} l rr@{}", r"Predicate & Union & Kept (\%) & Predicate & Union & Kept (\%)", c)
    tex = rf"""% Generated by research-paper/graphics/paperfigs/tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{{cap}}}
\label{{tab:keyretention}}
\small
\textbf{{(a)}}\\[2pt]
{ta}

\vspace{{8pt}}
\textbf{{(b)}}\\[2pt]
{tb}

\vspace{{8pt}}
\textbf{{(c)}}\\[2pt]
{tc}
\end{{table}}
"""
    a, b, c = out[False]
    md = ("**(a)**\n\n" + _md(["Class", "Union", "Retained", "Retention (%)", "Both (%)"], a)
          + "\n\n**(b)**\n\n" + _md(["Model", "Entity: both", "Entity: one", "Relation: both", "Relation: one",
                                     "Label: both", "Label: one"], b)
          + "\n\n**(c)**\n\n" + _md(["Predicate", "Union", "Kept (%)"] * 2, c)
          + "\n\n" + cap.replace("$n =$", "n =") + "\n")
    return _write("tableS5_key_retention", tex, md)


