def _num(x: float, nd: int, tex: bool, sign: bool = False) -> str:
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$" if tex else "−")


def _ci(ci, tex: bool) -> str:
    return f"[{_num(ci[0], 3, tex, True)}, {_num(ci[1], 3, tex, True)}]"


def _p(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _head2(names: list[str], tex: bool) -> list[str]:
    if tex:
        return [r"\shortstack{" + r"\\".join(HEAD2[n]) + "}" for n in names]
    return names


def _tt(code: str, tex: bool) -> str:
    return rf"\texttt{{{code.replace('_', chr(92) + '_')}}}" if tex else f"`{code}`"


def _md(header: list[str], rows: list[list[str]]) -> str:
    return ("| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
            + "\n".join("| " + " | ".join(r) + " |" for r in rows))


def _tex_table(label: str, caption: str, colspec: str, head: str, body: str, size: str = r"\small",
               env: str = "tabular") -> str:
    width = r"{\linewidth}" if env == "tabularx" else ""
    return rf"""% Generated by research-paper/graphics/paperfigs/tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{{caption}}}
\label{{{label}}}
{size}
\begin{{{env}}}{width}{{{colspec}}}
\toprule
{head}
\midrule
{body}
\bottomrule
\end{{{env}}}
\end{{table}}
"""


def _group_rows(groups: list[tuple[str, list[list[str]]]], ncol: int, tex: bool) -> tuple[str, list[list[str]]]:
    """Rows under bold group headings: LaTeX body text and Markdown rows."""
    if tex:
        parts = []
        for k, (title, rows) in enumerate(groups):
            if k:
                parts.append(r"\addlinespace")
            parts.append(rf"\multicolumn{{{ncol}}}{{@{{}}l}}{{\textit{{{title}}}}} \\")
            parts += [r"\quad " + " & ".join(r) + r" \\" for r in rows]
        return "\n".join(parts), []
    md = []
    for title, rows in groups:
        md.append([f"*{title}*"] + [""] * (ncol - 1))
        md += rows
    return "", md


# --------------------------------------------------------------------------- Table 3 (composition)
def table3_composition() -> list[Path]:
    comp = data.revision()["composition"]
    scored = data.scored_items()
    rights = data.rights()
    group = {d["id"]: d["split_group"] for d in scored}
    n_g = collections.Counter(group.values())
    G = len(n_g)

    def tally(sel) -> dict:
        its = [d for d in scored if sel(d)]
        return {"figures": len(its), "works": len({d["source"]["book_id"] for d in its}),
                "groups": len({group[d["id"]] for d in its}),
                "headline_weight": sum(1 / (G * n_g[group[d["id"]]]) for d in its)}

    year = {d["id"]: rights[d["source"]["book_id"]]["publication_year"] for d in scored}
    period = {lab: tally(lambda d, f=f: f(year[d["id"]])) for lab, f in PERIODS.values()}
    for key, (lab, _) in PERIODS.items():
        if period[lab]["figures"] != data.outline_numbers()["period"][key]["n"]:
            raise RuntimeError(f"period {key}: count differs from outline_numbers.json")
    dtype = {d["id"]: d["automatic_metadata"]["diagram_type"]["label"] for d in scored}
    ftype = {"Geometry": tally(lambda d: dtype[d["id"]] == "geometry"),
             "Graphs and plots": tally(lambda d: dtype[d["id"]] == "graph_plot"),
             "Other": tally(lambda d: dtype[d["id"]] not in ("geometry", "graph_plot"))}
    total = tally(lambda d: True)

    def dim(prefix: str, names=None) -> dict:
        rows = {k.split("|", 1)[1]: v for k, v in comp.items() if k.startswith(prefix + "|")}
        rows = dict(sorted(rows.items(), key=lambda kv: -kv[1]["figures"]))
        return {(names or {}).get(k, k[:1].upper() + k[1:]): v for k, v in rows.items()}

    groups = [("Period", period), ("Genre", dim("genre", {"book": "Book", "journal article": "Journal article"})),
              ("Language of the work", dim("language", LANGUAGE)), ("Digitization pathway", dim("pathway")),
              ("Repository", dim("repository")), ("Figure type", ftype)]
    for title, rows in groups:
        if sum(v["figures"] for v in rows.values()) != total["figures"]:
            raise RuntimeError(f"{title}: rows do not sum to N")

    def row(lab, v):
        return [lab, f"{v['figures']:,}", f"{v['works']}", f"{v['groups']}", f"{100 * v['headline_weight']:.1f}"]

    out = {}
    for tex in (True, False):
        g = [(t, [row(lab, v) for lab, v in rows.items()]) for t, rows in groups]
        body, md = _group_rows(g, 5, tex)
        tot = row("Total", total)
        out[tex] = (body + "\n\\midrule\n" + " & ".join(tot) + r" \\") if tex else md + [[f"**{c}**" for c in tot]]
    cap = (f"Composition of the scored set ($N =$ {total['figures']:,} figures, {total['works']} works, $G = {G}$ "
           f"source groups). Weight: share of the headline $H$, which weights every source group equally.")
    cap_md = cap.replace("$N =$", "N =").replace(f"$G = {G}$", f"G = {G}").replace("$H$", "H")
    head = ["", "Figures", "Works", "Groups", "Weight (%)"]
    tex = _tex_table("tab:composition", cap, r"@{}l rrrr@{}", " & ".join(head).replace("%", r"\%") + r" \\", out[True])
    return _write("table3_composition", tex, _md(head, out[False]) + f"\n\n{cap_md}\n")


