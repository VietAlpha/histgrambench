"""Tables 1-3 of the article, written as LaTeX (booktabs) and Markdown into research-paper/graphics/.

Every number is read from the run artifacts through `data` (score report, item records, answer keys,
registered thresholds), never typed in.
"""
from __future__ import annotations

import collections
from pathlib import Path

from . import data, style

OUT = Path(__file__).resolve().parents[1]


def _write(name: str, tex: str, md: str) -> list[Path]:
    paths = [OUT / f"{name}.tex", OUT / f"{name}.md"]
    paths[0].write_text(tex, encoding="utf-8")
    paths[1].write_text(md, encoding="utf-8")
    return paths


def _simple_table(name: str, label: str, caption: tuple[str, str], header: tuple[list[str], list[str]],
                  rows: tuple[list[list[str]], list[list[str]]], colspec: str) -> list[Path]:
    """Plain booktabs table (tabularx, full width) plus its Markdown twin. Each argument pair is (LaTeX, Markdown);
    LaTeX cells are written as given (math allowed)."""
    body = "\n".join(" & ".join(r) + r" \\" for r in rows[0])
    tex = rf"""% Generated by research-paper/graphics/paperfigs/tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{{caption[0]}}}
\label{{{label}}}
\small
\begin{{tabularx}}{{\linewidth}}{{{colspec}}}
\toprule
{" & ".join(header[0])} \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\end{{table}}
"""
    md = ("| " + " | ".join(header[1]) + " |\n|" + "---|" * len(header[1]) + "\n"
          + "\n".join("| " + " | ".join(r) + " |" for r in rows[1]) + f"\n\n{caption[1]}\n")
    return _write(name, tex, md)


