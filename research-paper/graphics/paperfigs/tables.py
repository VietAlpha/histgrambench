# --------------------------------------------------------------------------- Table 7 (page text)
def table7_page_text() -> list[Path]:
    pt = data.revision()["page_text"]
    on = data.outline_numbers()
    q = data.thresholds().value("bh_q")
    order = data.model_order("A")
    tests, bh = pt["tests"], pt["bh_adjusted"]
    cols = ["all", "text", "no_text", "no_text_groups_le3", "no_text_groups_gt3"]
    G = {c: tests[f"{data.SHORT[order[0]]}|{c}"]["G"] for c in cols}
    for m in order:
        if any(tests[f"{data.SHORT[m]}|{c}"]["G"] != G[c] for c in cols):
            raise RuntimeError("subset G differs between models")
    pooled = {"all": on["pooled_BA_all"], "text": on["pooled_BA_text"], "no_text": on["pooled_BA_notext"]}
    if abs(pooled["all"]["estimate"] - data.scores()["context_effect"]["pooled"]["estimate"]) > 1e-9:
        raise RuntimeError("pooled B - A differs from the score report")

    out = {}
    for tex in (True, False):
        rows = []
        for m in order:
            s = data.SHORT[m]
            est, ci = [], []
            for c in cols:
                t = tests[f"{s}|{c}"]
                p = f" ({_p(bh[f'{s}|{c}'])})" if f"{s}|{c}" in bh else ""
                est.append(_num(t["est"], 3, tex, True) + p)
                ci.append(_ci(t["ci"], tex) if c in pooled else "")
            dv = on["dvalid"][style.MODEL_NAMES[m]]
            est += [_num(tests[f"{s}|item_weighted_all"], 3, tex, True),
                    _num(100 * dv["text"], 1, tex, True), _num(100 * dv["notext"], 1, tex, True)]
            ci += [""] * 3
            name = style.MODEL_NAMES[m]   # LaTeX: name split over the estimate and interval lines
            rows.append([HEAD2[name][0] if tex else name] + est)
            rows.append([" ".join(HEAD2[name][1:]) if tex else ""] + ci)
        dash = "--" if tex else "—"
        rows.append(["Pooled"] + [_num(pooled[c]["estimate"], 3, tex, True) if c in pooled else dash for c in cols]
                    + [dash] * 3)
        rows.append([""] + [_ci(pooled[c]["ci"], tex) if c in pooled else "" for c in cols] + [""] * 3)
        out[tex] = rows
    cap = (f"Page text: paired difference B $-$ A in $H$ by subset, with 95\\% group-$t$ intervals ($df = G - 1$). "
           f"Parentheses: BH-adjusted $p$ over the {len(bh)} per-model tests of the first three columns "
           f"(separated at $q = {q:.2f}$ when $\\le {q:.2f}$). Text-free plates are also split into groups of at most three and of more "
           f"than three plates (estimates only). Item-wt.: "
           f"item-weighted B $-$ A over all figures. $\\Delta$Valid: change in the valid share, percentage points. "
           f"{G['text']} + {G['no_text']} exceeds {G['all']} because {pt['groups']['both']} groups contain both "
           f"kinds of figure.")
    cap_md = (cap.replace("B $-$ A", "B − A").replace("$H$", "H").replace("95\\%", "95%").replace("group-$t$", "group-t")
              .replace("$df = G - 1$", "df = G − 1").replace("$p$", "p").replace(f"$q = {q:.2f}$", f"q = {q:.2f}")
              .replace(f"$\\le {q:.2f}$", f"≤ {q:.2f}").replace("$\\Delta$", "Δ"))
    labels = ["All", "Page text", "Text-free", r"Text-free, $\le$3", "Text-free, $>$3"]
    head_tex = ("Model & " + " & ".join(rf"\shortstack{{{lab}\\$G = {G[c]}$}}" for lab, c in zip(labels, cols))
                + r" & Item-wt. & \shortstack{$\Delta$Valid\\text} & \shortstack{$\Delta$Valid\\text-free} \\")
    body = "\n".join(" & ".join(r) + r" \\" + (r"\addlinespace[2pt]" if k % 2 and k < len(out[True]) - 3 else "")
                     for k, r in enumerate(out[True][:-2]))
    body += "\n\\midrule\n" + "\n".join(" & ".join(r) + r" \\" for r in out[True][-2:])
    tex = _tex_table("tab:pagetext", cap, r"@{}l ccccc c rr@{}", head_tex, body,
                     size=r"\scriptsize\setlength{\tabcolsep}{3pt}")
    plain = [lab.replace(r"$\le$", "≤").replace("$>$", ">") for lab in labels]
    md_head = ["Model"] + [f"{lab} (G = {G[c]})" for lab, c in zip(plain, cols)] \
        + ["Item-wt.", "ΔValid text (pp)", "ΔValid text-free (pp)"]
    return _write("table7_page_text", tex, _md(md_head, out[False]) + f"\n\n{cap_md}\n")


